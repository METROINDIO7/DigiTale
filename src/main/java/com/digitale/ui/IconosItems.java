    /** AssetPath del icono para un id corto, o null si no hay. */
    public static String iconoDe(String corto) {
        if (corto == null || corto.isEmpty()) return null;
        String r = MAPA.get(corto);
        if (r != null) return r;
        if (corto.startsWith("Digitama_")) {
            String suf = corto.substring("Digitama_".length());
            return "Icons/ItemsGenerated/Digitamas/Icon_Digitama_" + suf + ".png";
        }
        if (corto.startsWith("Dato_Incubacion_")) {
            return "Icons/ItemsGenerated/Icon_Dato_Incuvacion.png";
        }
        return null;
    }
